"""
scripts/apply_title_and_relabeling.py

Updates:
1. Title: Stable but Wrong: Why Consensus Clustering Can Fail in High Dimensions, and What Helps
   Running head: [Why Consensus Clustering Can Fail in High Dimensions]
   Keywords: Stability-accuracy gap, consensus clustering, high-dimensional noise, clustering ensembles, bipartite anchor graphs, feature gating, distance concentration, inductive out-of-sample projection.
2. Relabels ICC-v2 -> GAC pipeline (or GAC) and ICC-v1 -> ungated anchor consensus.
3. Adds Code availability note: "The repository name icc-clustering is historical and unrelated to the Iterative Consensus Clustering of Race and Meyer."
4. Integrates verified Related Work citations:
   - Senbabaoglu et al. (2014)
   - Race & Meyer (2013)
   - Lindenbaum et al. (2021)
   - Chen (2026)
   - Fern & Brodley (2003)
5. Updates README.md and pyproject.toml
"""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

NEW_TITLE = "Stable but Wrong: Why Consensus Clustering Can Fail in High Dimensions, and What Helps"
SHORT_TITLE = "Why Consensus Clustering Can Fail in High Dimensions"
NEW_KEYWORDS = "Stability-accuracy gap, consensus clustering, high-dimensional noise, clustering ensembles, bipartite anchor graphs, feature gating, distance concentration, inductive out-of-sample projection."
CODE_NOTE = " The repository name icc-clustering is historical and unrelated to the Iterative Consensus Clustering of Race and Meyer."


def update_tex_file(path: Path):
    text = path.read_text(encoding="utf-8")

    # 1. Title and running head
    text = re.sub(
        r"\\title\[[^\]]*\]\{[^}]*\}",
        f"\\\\title[{SHORT_TITLE}]{{{NEW_TITLE}}}",
        text,
        count=1
    )

    # 2. Keywords
    text = re.sub(
        r"\\keywords\{[^}]*\}",
        f"\\\\keywords{{{NEW_KEYWORDS}}}",
        text,
        count=1
    )

    # 3. Code availability
    if "The repository name icc-clustering is historical" not in text:
        text = text.replace(
            r"\url{https://github.com/AkashKundu114/icc-clustering} (release tag \texttt{v2.1.0}).",
            r"\url{https://github.com/AkashKundu114/icc-clustering} (release tag \texttt{v2.1.0})." + CODE_NOTE
        )

    # 4. Related work additions
    # 4a. Senbabaoglu & Race & Meyer in Sec 2.1
    if "senbabaoglu2014critical" not in text:
        sec21_anchor = r"\subsection{Cluster Ensembles and Consensus Functions}"
        sec21_insert = (
            "\nConsensus clustering aggregates diverse partitions generated by base algorithms into an integrated consensus solution. "
            "However, Senbabaoglu et al.~\\cite{senbabaoglu2014critical} reassessed the empirical validity of consensus clustering in class discovery, "
            "demonstrating that high consensus stability often reflects clusterer-induced geometric artifacts rather than genuine cluster structure, "
            "a pathology directly anticipating the stability-accuracy gap examined in this work. "
            "To address cluster count ambiguity in consensus pipelines, Race and Meyer~\\cite{race2013determining} investigated iterative consensus clustering (ICC), "
            "successively pruning confident cluster assignments."
        )
        # Replace the first sentence of Sec 2.1
        text = text.replace(
            r"\subsection{Cluster Ensembles and Consensus Functions}" + "\n" + r"Consensus clustering aggregates diverse partitions generated by base algorithms into an integrated consensus solution.",
            r"\subsection{Cluster Ensembles and Consensus Functions}" + sec21_insert
        )

    # 4b. Lindenbaum & Chen in Sec 2.3
    if "lindenbaum2021differentiable" not in text:
        sec23_target = r"Witten and Tibshirani~\cite{witten2010framework} addressed high-dimensional clustering via Sparse K-Means, introducing an $L_1$ penalty on feature weights to screen uninformative dimensions. However, iterative sparse feature weighting incurs significant computational overhead and assumes convex cluster geometry."
        sec23_insert = (
            "Witten and Tibshirani~\\cite{witten2010framework} addressed high-dimensional clustering via Sparse K-Means, "
            "introducing an $L_1$ penalty on feature weights to screen uninformative dimensions. "
            "Beyond convex penalties, Lindenbaum et al.~\\cite{lindenbaum2021differentiable} formulated differentiable unsupervised feature selection using a gated Laplacian, "
            "learning continuous soft feature gates via stochastic gradient descent on graph eigenvalues. "
            "More recently, Chen~\\cite{chen2026data} developed a data-informed variational clustering framework incorporating continuous feature gating for noisy high-dimensional settings. "
            "In contrast to continuous variational relaxations or iterative gradient-based feature gating which incur substantial optimization overhead, "
            "Bimodality-Gated Subspace Selection (BGSS) performs strictly marginal bimodality screening in linear time $O(N \\cdot D)$, enabling fast screening before ensemble generation."
        )
        text = text.replace(sec23_target, sec23_insert)

    # 5. Relabel ICC-v2 -> GAC pipeline (or GAC) and ICC-v1 -> ungated anchor consensus
    # Specific phrases first
    replacements = [
        (r"Inductive Consensus Clustering (ICC-v2)", "Gated Anchor Consensus (GAC) Pipeline"),
        (r"Inductive Consensus Clustering (ICC)", "Gated Anchor Consensus (GAC) pipeline"),
        (r"the \textbf{Inductive Consensus Clustering (ICC)} pipeline", r"the \textbf{Gated Anchor Consensus (GAC)} pipeline"),
        (r"Bipartite ICC-v2", "Bipartite GAC Pipeline"),
        (r"T_{\text{ICC-v2}}", r"T_{\text{GAC}}"),
        (r"Full ICC-v2", "Full GAC Pipeline"),
        (r"ICC-v2 (Ours)", "GAC Pipeline (Ours)"),
        (r"ICC-v2 (BGSS+Anchor)", "GAC Pipeline (BGSS+Anchor)"),
        (r"ICC-v2 (BGSS Gating)", "GAC Pipeline (BGSS Gating)"),
        (r"ICC-v2", "GAC pipeline"),
        (r"ICC-v1 (Legacy)", "Ungated Anchor Consensus (Legacy)"),
        (r"ICC-v1", "ungated anchor consensus"),
    ]

    for old_s, new_s in replacements:
        text = text.replace(old_s, new_s)

    path.write_text(text, encoding="utf-8")
    print(f"[*] Updated: {path}")


def update_readme_and_pyproject():
    readme_path = ROOT / "README.md"
    if readme_path.exists():
        txt = readme_path.read_text(encoding="utf-8")
        txt = re.sub(
            r"# When Do Feature Gating and Anchor Consensus Help High-Dimensional Clustering\? \(ICC-v2\)",
            f"# {NEW_TITLE}",
            txt
        )
        txt = re.sub(
            r"\*\*\"When Do Feature Gating and Anchor Consensus Help High-Dimensional Clustering\? An Empirical and Geometric Analysis\"\*\*",
            f'**"{NEW_TITLE}"**',
            txt
        )
        txt = txt.replace(
            "title     = {When Do Feature Gating and Anchor Consensus Help High-Dimensional Clustering? An Empirical and Geometric Analysis},",
            f"title     = {{{NEW_TITLE}}},"
        )
        readme_path.write_text(txt, encoding="utf-8")
        print(f"[*] Updated: {readme_path}")

    pyproject_path = ROOT / "pyproject.toml"
    if pyproject_path.exists():
        txt = pyproject_path.read_text(encoding="utf-8")
        txt = re.sub(
            r'description = "Reference implementation: When Do Feature Gating and Anchor Consensus Help High-Dimensional Clustering\? An Empirical and Geometric Analysis"',
            f'description = "Reference implementation: {NEW_TITLE}"',
            txt
        )
        pyproject_path.write_text(txt, encoding="utf-8")
        print(f"[*] Updated: {pyproject_path}")


def main():
    update_tex_file(ROOT / "paper" / "main.tex")
    update_tex_file(ROOT / "springer_manuscript" / "main.tex")
    update_readme_and_pyproject()
    print("[+] All title, metadata, and relabeling updates applied successfully.")


if __name__ == "__main__":
    main()
