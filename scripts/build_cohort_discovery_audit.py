def build_reviewed_download_manifest() -> Path:
    out_path = AUDIT_DIR / "download_manifest_reviewed.csv"
    fields = ["cohort_id", "url", "relative_path", "expected_sha256", "license_reviewed"]
    rows = []
    for c in COHORT_AUDIT_DATA:
        if c.get("download_candidate"):
            acc = c["accession"]
            prefix = acc[:-3] + "nnn"
            url = f"https://ftp.ncbi.nlm.nih.gov/geo/series/{prefix}/{acc}/matrix/{acc}_series_matrix.txt.gz"
            rel = f"{acc}/{acc}_series_matrix.txt.gz"
            rows.append({
                "cohort_id": c["cohort_id"],
                "url": url,
                "relative_path": rel,
                "expected_sha256": "",  # Empty for initial acquisition, computed by downloader
                "license_reviewed": "YES",  # Documented academic open access
            })

    with out_path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fields)
        writer.writeheader()
        writer.writerows(rows)
    print(f"Saved {len(rows)} reviewed candidates to {out_path}")
    return out_path


