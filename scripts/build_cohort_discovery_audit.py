def build_eligibility_decisions_csv() -> Path:
    out_path = AUDIT_DIR / "eligibility_decisions.csv"
    fields = [
        "cohort_id", "accession", "disease", "n_samples", "n_features_raw", "d_over_n",
        "gate_a_human", "gate_b_cancer", "gate_c_expression", "gate_d_min_samples",
        "gate_e_min_features", "gate_f_mapping", "gate_g_license", "gate_h_publication",
        "gate_i_independence", "label_type", "primary_label_name", "total_score",
        "eligibility_tier", "eligibility_decision", "decision_rationale"
    ]
    rows = []
    for c in COHORT_AUDIT_DATA:
        g = c["gates"]
        rows.append({
            "cohort_id": c["cohort_id"],
            "accession": c["accession"],
            "disease": c["disease"],
            "n_samples": c["n_samples"],
            "n_features_raw": c["n_features_raw"],
            "d_over_n": f"{c['d_over_n']:.2f}",
            "gate_a_human": "PASS" if g["gate_a_human"] else "FAIL",
            "gate_b_cancer": "PASS" if g["gate_b_cancer"] else "FAIL",
            "gate_c_expression": "PASS" if g["gate_c_expression"] else "FAIL",
            "gate_d_min_samples": "PASS" if g["gate_d_min_samples"] else "FAIL",
            "gate_e_min_features": "PASS" if g["gate_e_min_features"] else "FAIL",
            "gate_f_mapping": "PASS" if g["gate_f_mapping"] else "FAIL",
            "gate_g_license": "PASS" if g["gate_g_license"] else "FAIL",
            "gate_h_publication": "PASS" if g["gate_h_publication"] else "FAIL",
            "gate_i_independence": "PASS" if g["gate_i_independence"] else "FAIL",
            "label_type": c["label_type"],
            "primary_label_name": c["label_name"],
            "total_score": c["total_score"],
            "eligibility_tier": c["eligibility_tier"],
            "eligibility_decision": c["eligibility_decision"],
            "decision_rationale": c["decision_rationale"],
        })

    with out_path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fields)
        writer.writeheader()
        writer.writerows(rows)
    print(f"Saved {len(rows)} eligibility decisions to {out_path}")
    return out_path


def build_exclusion_log_csv() -> Path:
    out_path = AUDIT_DIR / "exclusion_log.csv"
    fields = [
        "cohort_id", "accession", "category", "reason", "failed_gates",
        "sample_ids_excluded", "evidence_reference", "resolution_status"
    ]
    rows = []
    for c in COHORT_AUDIT_DATA:
        if c["eligibility_tier"] in ["REJECT", "TIER_C"] or "REJECT" in c["eligibility_decision"]:
            failed = [k for k, v in c["gates"].items() if not v]
            rows.append({
                "cohort_id": c["cohort_id"],
                "accession": c["accession"],
                "category": c["eligibility_tier"],
                "reason": c["decision_rationale"],
                "failed_gates": "; ".join(failed) if failed else "None (Label B4 / Design)",
                "sample_ids_excluded": f"All {c['n_samples']} samples",
                "evidence_reference": f"{c['repository']} {c['accession']}; DOI: {c['publication_doi']}",
                "resolution_status": "EXCLUDED_FROM_PRIMARY_BENCHMARK",
            })

    with out_path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fields)
